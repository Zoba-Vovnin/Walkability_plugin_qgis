    def insert_point_to_graph(self, point, name):
        """Вставка одной точки в граф."""
        px, py = point.x(), point.y()
        node = (round(px, COORD_PRECISION), round(py, COORD_PRECISION))
        
        if node in self.node_coords:
            return node
        
        min_dist = float('inf')
        nearest_edge = None
        proj_point = None

        candidate_edge_keys = []
        if self.edge_spatial_index is not None:
            nearest_ids = self.edge_spatial_index.nearestNeighbor(point, 24)
            candidate_edge_keys = [
                self.edge_lookup_by_fid[edge_fid]
                for edge_fid in nearest_ids
                if edge_fid in self.edge_lookup_by_fid
            ]

        if not candidate_edge_keys:
            candidate_edge_keys = list(self.edge_data.keys())

        for edge_key in candidate_edge_keys:
            n1, n2 = edge_key
            p1, p2 = self.node_coords[n1], self.node_coords[n2]
            qx, qy, dist = self.project_point_on_segment(px, py, p1, p2)
            if dist < min_dist:
                min_dist = dist
                nearest_edge = (n1, n2)
                proj_point = (round(qx, COORD_PRECISION), round(qy, COORD_PRECISION))
        
        if nearest_edge is None:
            self.log(f"Не найдено ребро для точки {name}", Qgis.Warning)
            logging.warning(f"Точка {name} не привязана к графу")
            return None
        
        self.node_coords[node] = point
        self.node_coords[proj_point] = QgsPointXY(proj_point[0], proj_point[1])
        
        dist_to_proj = math.sqrt((px - proj_point[0])**2 + (py - proj_point[1])**2)
        self.graph[node][proj_point] = max(dist_to_proj, MIN_WEIGHT)
        self.graph[proj_point][node] = max(dist_to_proj, MIN_WEIGHT)
        self.register_edge_data(node, proj_point, max(dist_to_proj, MIN_WEIGHT), max(dist_to_proj, MIN_WEIGHT))
        
        n1, n2 = nearest_edge
        edge_key = tuple(sorted([n1, n2]))
        
        edge_info = self.get_edge_data_by_key(edge_key)
        if edge_info is not None:
            p1 = self.node_coords[n1]
            p2 = self.node_coords[n2]
            dist1 = math.sqrt((proj_point[0] - p1.x())**2 + (proj_point[1] - p1.y())**2)
            dist2 = math.sqrt((proj_point[0] - p2.x())**2 + (proj_point[1] - p2.y())**2)
            
            total_len = edge_info['length']
            if total_len > 0:
                ratio = edge_info['weight'] / total_len
                weight1 = dist1 * ratio
                weight2 = dist2 * ratio
            else:
                weight1 = dist1
                weight2 = dist2
            
            if n2 in self.graph[n1]:
                del self.graph[n1][n2]
            if n1 in self.graph[n2]:
                del self.graph[n2][n1]
            
            self.graph[n1][proj_point] = max(weight1, MIN_WEIGHT)
            self.graph[proj_point][n1] = max(weight1, MIN_WEIGHT)
            self.graph[proj_point][n2] = max(weight2, MIN_WEIGHT)
            self.graph[n2][proj_point] = max(weight2, MIN_WEIGHT)
            self.register_edge_data(n1, proj_point, max(dist1, MIN_WEIGHT), max(weight1, MIN_WEIGHT), template=edge_info)
            self.register_edge_data(proj_point, n2, max(dist2, MIN_WEIGHT), max(weight2, MIN_WEIGHT), template=edge_info)
        
        return node

    def project_point_on_segment(self, px, py, p1, p2):
        """Проекция точки на отрезок."""
        ax, ay = p1.x(), p1.y()
        bx, by = p2.x(), p2.y()
        abx, aby = bx - ax, by - ay
        ab2 = abx * abx + aby * aby
        if ab2 < 1e-12:
            return ax, ay, math.sqrt((px - ax)**2 + (py - ay)**2)
        t = max(0.0, min(1.0, ((px - ax) * abx + (py - ay) * aby) / ab2))
        qx = ax + t * abx
        qy = ay + t * aby
        dist = math.sqrt((px - qx)**2 + (py - qy)**2)
        return qx, qy, dist

    def dijkstra(self, start_node, end_node, graph=None):
        """Алгоритм Дейкстры для поиска кратчайшего пути."""
        g = graph if graph is not None else self.graph
        if start_node not in g or end_node not in g:
            return None, float('inf')
        
        dist = {start_node: 0.0}
        prev = {}
        pq = [(0.0, 0, start_node)]
        visited = set()
        counter = 0
        
        while pq:
            d_u, _, u = heapq.heappop(pq)
            if u in visited:
                continue
            visited.add(u)
            if u == end_node:
                break
            for v, weight in g[u].items():
                if v in visited:
                    continue
                new_dist = d_u + weight
                if new_dist < dist.get(v, float('inf')):
                    dist[v] = new_dist
                    prev[v] = u
                    counter += 1
                    heapq.heappush(pq, (new_dist, counter, v))
        
        if dist.get(end_node, float('inf')) == float('inf'):
            return None, float('inf')
        
        path = []
        current = end_node
        while current is not None:
            path.append(current)
            current = prev.get(current)
        path.reverse()
        return path, dist[end_node]

    def make_path_cache_key(self, start_node, end_node):
        """Ключ кэша маршрута между двумя узлами."""
        return (start_node, end_node)

    def get_shortest_path_cached(self, start_node, end_node):
        """Получить кратчайший путь из кэша или рассчитать."""
        cache_key = self.make_path_cache_key(start_node, end_node)
        cached = self.path_cache.get(cache_key)
        if cached is not None:
            return cached

        path, weight = self.dijkstra(start_node, end_node)
        self.path_cache[cache_key] = (path, weight)

        if path:
            reverse_key = self.make_path_cache_key(end_node, start_node)
            self.path_cache[reverse_key] = (list(reversed(path)), weight)

        return path, weight

    def calculate_nearest_endpoint_routes(self, start_points, end_points):
        """Расчет кратчайшего пути от каждой начальной точки до ближайшей конечной."""
        self.log("\n── Расчет кратчайших путей до ближайших конечных точек ──")
        self.update_progress(70)
        self.path_cache = {}

        nearest_routes = []
        routes_ok = 0
        routes_fail = 0

        self.log(f"Начальных точек: {len(start_points)}, Конечных точек: {len(end_points)}")
        self.log(f"✓ Все расчёты длины выполняются в {ANALYSIS_CRS} (метры)")
        logging.info(f"Расчет кратчайших путей для {len(start_points)} начальных точек")
        logging.info(f"Система координат для расчёта длины: {ANALYSIS_CRS} (метры)")

        for start_name, start_node in start_points:
            min_weight = float('inf')
            best_end_name = None
            best_end_node = None
            best_path = None

            for end_name, end_node in end_points:
                if start_node == end_node:
                    continue

                path, weight = self.get_shortest_path_cached(start_node, end_node)
                if path is not None and weight < min_weight:
                    min_weight = weight
                    best_end_name = end_name
                    best_end_node = end_node
                    best_path = path

            if best_path is None:
                self.log(f"✗ {start_name}: не найдено доступной конечной точки", Qgis.Warning)
                routes_fail += 1
            else:
                nearest_routes.append({
                    'start_name': start_name,
                    'end_name': best_end_name,
                    'start_node': start_node,
                    'end_node': best_end_node,
                    'path': best_path,
                    'weight': min_weight,
                    'vertices': len(best_path),
                    'is_nearest': True
                })
                routes_ok += 1
                self.log(f"✓ [{routes_ok}] {start_name} → {best_end_name} (ближайшая) вес={min_weight:.4f}")

        self.log(f"\n✅ Успешно: {routes_ok}  |  ✗ Ошибок: {routes_fail}")
        logging.info(f"Рассчитано кратчайших путей: успешно {routes_ok}, ошибок {routes_fail}")
        return nearest_routes

