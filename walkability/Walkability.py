    def build_graph(self, edges_layer, width_field=None, surface_field=None):
        self.log("\n── Построение графа ──")
        self.update_progress(20)
        
        # Сохраняем CRS слоя 
        self.edges_crs = edges_layer.crs()
        
        # Проверка проекции
        if self.edges_crs.authid() != ANALYSIS_CRS:
            self.log(
                f"⚠️ ВНИМАНИЕ: Слой не в {ANALYSIS_CRS}! "
                f"Текущая CRS: {self.edges_crs.authid()}. "
                f"Расчёт длины может быть неточным!",
                Qgis.Warning
            )
            logging.warning(
                f"Граф строится в CRS {self.edges_crs.authid()}, "
                f"ожидалась {ANALYSIS_CRS}"
            )
        else:
            self.log(f"✓ Слой в метрической CRS: {ANALYSIS_CRS}")
            logging.info(f"Граф строится в {ANALYSIS_CRS} (метры)")
        
        self.graph = defaultdict(dict)
        self.node_coords = {}
        self.massive_edge_data = []
        self.edge_data = {}
        self.edge_indices_by_key = defaultdict(list)
        self.edge_spatial_index = None
        self.edge_lookup_by_fid = {}
        edge_count = 0
        
        for feat in edges_layer.getFeatures():
            geom = feat.geometry()
            if not geom or geom.isEmpty():
                continue
            
            width_val = feat[width_field] if width_field else None
            surface_val = feat[surface_field] if surface_field else None
            
            weight_width = self.calc_width_weight(width_val)
            surface_coeff = self.calc_surface_coeff(surface_val)
            
            if geom.isMultipart():
                lines = geom.asMultiPolyline()
            else:
                lines = [geom.asPolyline()]
            
            for line in lines:
                for i in range(len(line) - 1):
                    p1 = line[i]
                    p2 = line[i + 1]
                    
                    n1 = (round(p1.x(), COORD_PRECISION), round(p1.y(), COORD_PRECISION))
                    n2 = (round(p2.x(), COORD_PRECISION), round(p2.y(), COORD_PRECISION))
                    
                    self.node_coords[n1] = p1
                    self.node_coords[n2] = p2
                    
                    length = math.sqrt((p2.x() - p1.x())**2 + (p2.y() - p1.y())**2)
                    weight = length * weight_width * surface_coeff
                    
                    self.graph[n1][n2] = weight
                    self.graph[n2][n1] = weight
                    
                    self.register_edge_data(
                        n1, n2, length, weight,
                        template={
                            'weight_width': weight_width,
                            'surface_coeff': surface_coeff,
                            'near_park': False,
                            'park_proximity': PARK_PROXIMITY_FAR
                        }
                    )
                    edge_count += 1
        
        self.log(f"Построен граф: {len(self.node_coords)} вершин, {edge_count} рёбер")
        logging.info(f"Построен граф: {len(self.node_coords)} вершин, {edge_count} рёбер")
        self.build_edge_spatial_index()
        return True

    def calc_width_weight(self, width_val):
        """Вычисление коэффициента ширины."""
        if self.is_missing_weight_value(width_val):
            return 1.0
        try:
            w = float(width_val)
            if w > 0:
                return max(1.0 - 1.0 / (WIDTH_SCALE * w), MIN_WEIGHT)
        except (TypeError, ValueError):
            pass
        return 1.0

    def calc_surface_coeff(self, surface_val):
        """Вычисление коэффициента покрытия."""
        if self.is_missing_weight_value(surface_val):
            return 1.0
        surface_str = str(surface_val).strip().lower()
        return SURFACE_COEFFS.get(surface_str, 1.0)

