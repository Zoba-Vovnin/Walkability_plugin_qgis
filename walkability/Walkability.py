    def run(self):
        """Run method that performs all the real work"""
        if self.dlg is None:
            self.dlg = Urban_researchDialog()
            self.setup_ui_connections()
        self.dlg.show()
        
        # В PyQt6 exec_() переименован в exec()
        if IS_QGIS4:
            result = self.dlg.exec()
        else:
            result = self.dlg.exec_()
            
        if result:
            self.start_processing_task()
