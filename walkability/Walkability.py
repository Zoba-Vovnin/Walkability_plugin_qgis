    def apply_density_weights(self, density_layer, density_field):
        """Применение весов плотности к рёбрам."""
        self.log("\n── Применение весов плотности ──")
        self.update_progress(40)
        
        if not density_layer or not density_field:
            self.log("Плотность не задана, пропускаем")
            logging.info("Плотность не задана – веса плотности не применялись")
            return
        
        spatial_index = QgsSpatialIndex(density_layer.getFeatures())
        density_dict = {}
        for feat in density_layer.getFeatures():
            geom = feat.geometry()
            if geom and not geom.isEmpty():
                density_val = feat[density_field]
                if self.is_missing_weight_value(density_val):
                    continue
                try:
                    dv = float(density_val)
                except (TypeError, ValueError):
                    continue
                if dv <= 0 or not math.isfinite(dv):
                    continue
                density_dict[feat.id()] = dv
        
        updated = 0
        for edge_key, edge_idx in self.edge_data.items():
            data = self.massive_edge_data[edge_idx]
            n1, n2 = edge_key
            p1, p2 = self.node_coords[n1], self.node_coords[n2]
            
            mid_x = (p1.x() + p2.x()) / 2
            mid_y = (p1.y() + p2.y()) / 2
            mid_point = QgsPointXY(mid_x, mid_y)
            
            nearest_ids = spatial_index.nearestNeighbor(mid_point, 1)
            if not nearest_ids:
                continue
            nid = nearest_ids[0]
            if nid not in density_dict:
                continue
            density_val = density_dict[nid]
            
            density_factor = 1.0 - DENSITY_THRESHOLD / density_val
            density_factor = abs(density_factor) if density_factor <= 0 else density_factor or MIN_WEIGHT
            
            old_weight = data['weight']
            new_weight = old_weight * density_factor
            data['weight'] = self.safe_weight(new_weight, data['length'])
            data['density_val'] = density_val
            data['density_factor'] = density_factor
            
            self.graph[n1][n2] = data['weight']
            self.graph[n2][n1] = data['weight']
            updated += 1
        
        self.log(f"Обновлено весов плотности: {updated}")
        logging.info(f"Применены веса плотности: обновлено {updated} рёбер")

    def apply_park_proximity(self, park_layer):
        self.log("\n── Применение весов парков ──")
        self.update_progress(50)
        
        if not park_layer:
            self.log("Парки не заданы, пропускаем")
            logging.info("Парки не заданы – веса близости к паркам не применялись")
            return
        
        self.build_park_spatial_index(park_layer)
        if not self.park_buffered_by_fid:
            self.log("Нет валидных парков")
            return
        
        near_count = 0
        for edge_key, edge_idx in self.edge_data.items():
            data = self.massive_edge_data[edge_idx]
            n1, n2 = edge_key
            p1, p2 = self.node_coords[n1], self.node_coords[n2]
            edge_geom = QgsGeometry.fromPolylineXY([p1, p2])
            
            near_park = False
            candidate_ids = self.park_spatial_index.intersects(edge_geom.boundingBox())
            for park_fid in candidate_ids:
                buff_geom = self.park_buffered_by_fid.get(park_fid)
                if buff_geom is None:
                    continue
                if edge_geom.intersects(buff_geom):
                    near_park = True
                    break
            
            if near_park:
                old_weight = data['weight']
                new_weight = old_weight * PARK_PROXIMITY_NEAR
                data['weight'] = self.safe_weight(new_weight, data['length'])
                data['near_park'] = True
                data['park_proximity'] = PARK_PROXIMITY_NEAR
                
                self.graph[n1][n2] = data['weight']
                self.graph[n2][n1] = data['weight']
                near_count += 1
        
        self.log(f"Рёбер вблизи парков: {near_count}")
        logging.info(f"Применены веса парков: {near_count} рёбер вблизи парков")

