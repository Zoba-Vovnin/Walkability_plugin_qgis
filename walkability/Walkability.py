    def build_edge_spatial_index(self):
        """Построение spatial index для рёбер графа."""
        self.edge_spatial_index = QgsSpatialIndex()
        self.edge_lookup_by_fid = {}
        fid = 0

        for edge_key in self.edge_data.keys():
            n1, n2 = edge_key
            p1 = self.node_coords[n1]
            p2 = self.node_coords[n2]
            edge_geom = QgsGeometry.fromPolylineXY([p1, p2])

            edge_feat = QgsFeature()
            edge_feat.setId(fid)
            edge_feat.setGeometry(edge_geom)
            self.edge_spatial_index.addFeature(edge_feat)
            self.edge_lookup_by_fid[fid] = edge_key
            fid += 1

        self.log(f"Построен spatial index рёбер: {len(self.edge_lookup_by_fid)}")

    def get_edge_data_by_key(self, edge_key):
        """Получить активные данные ребра по его ключу."""
        idx = self.edge_data.get(edge_key)
        if idx is None:
            return None
        if idx < 0 or idx >= len(self.massive_edge_data):
            return None
        return self.massive_edge_data[idx]

    def calculate_route_length_direct(self, path_nodes):

        if not path_nodes or len(path_nodes) < 2:
            return 0.0
        
        total_length = 0.0
        
        for i in range(len(path_nodes) - 1):
            n1 = path_nodes[i]
            n2 = path_nodes[i + 1]
            
            if n1 not in self.node_coords or n2 not in self.node_coords:
                self.log(f"Предупреждение: узел не найден в node_coords", Qgis.Warning)
                continue
                
            # Получаем координаты в EPSG:3857 (метры)
            p1 = self.node_coords[n1]  # QgsPointXY в EPSG:3857
            p2 = self.node_coords[n2]  # QgsPointXY в EPSG:3857
            
            # Евклидово расстояние в метрах (прямая формула для плоских координат)
            segment_length = math.sqrt((p2.x() - p1.x())**2 + (p2.y() - p1.y())**2)
            total_length += segment_length
        
        # Результат ВСЕГДА в метрах (EPSG:3857)
        return total_length

