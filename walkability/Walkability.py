    def process_data(self, params, task=None):
        """Основная функция обработки данных."""
        start_time = datetime.now()
        try:
            self.log("\n" + "="*60)
            self.log("НАЧАЛО ОБРАБОТКИ")
            self.log("="*60)
            self.set_progress(0, task)
            
            self.setup_file_logging(params["output_dir"])
            
            edges_layer = self.load_layer_from_file(params["edges_path"], "Дорожная сеть")
            if not edges_layer:
                raise Exception("Не удалось загрузить дорожную сеть")
            
            start_layer = self.load_layer_from_file(params["start_path"], "START точки")
            end_layer = self.load_layer_from_file(params["end_path"], "END точки")
            density_layer = self.load_layer_from_file(params["density_path"], "Плотность")
            park_layer = self.load_layer_from_file(params["park_path"], "Парки")

            edges_layer = self.preprocess_layer_for_analysis(edges_layer, "Дорожная сеть")
            if start_layer:
                start_layer = self.preprocess_layer_for_analysis(start_layer, "START точки")
            if end_layer:
                end_layer = self.preprocess_layer_for_analysis(end_layer, "END точки")
            if density_layer:
                density_layer = self.preprocess_layer_for_analysis(density_layer, "Плотность")
            if park_layer:
                park_layer = self.preprocess_layer_for_analysis(park_layer, "Парки")
            
            if not self.build_graph(edges_layer, params["width_field"], params["surface_field"]):
                raise Exception("Ошибка построения графа")
            
            self.apply_density_weights(density_layer, params["density_field"])
            self.apply_park_proximity(park_layer)
            
            start_points, end_points = self.insert_route_points(start_layer, end_layer, params["id_field"])
            if not start_points or not end_points:
                raise Exception("Нет точек для расчёта маршрутов")
            
            nearest_routes = self.calculate_nearest_endpoint_routes(start_points, end_points)

            self.export_results(params["output_dir"], start_points, end_points, nearest_routes)

            if params.get("add_layers_to_project", False):
                self.add_result_layers_to_project(params["output_dir"])
            
            self.set_progress(100, task)
            duration = (datetime.now() - start_time).total_seconds()
            
            self.log("\n" + "="*60)
            self.log("✅ ОБРАБОТКА ЗАВЕРШЕНА УСПЕШНО!")
            self.log("="*60)
            return {
                "routes_count": len(nearest_routes),
                "output_dir": params["output_dir"],
                "duration": duration,
                "layers_added": params.get("add_layers_to_project", False),
            }
        except Exception as e:
            self.log(f"\n❌ ОШИБКА: {str(e)}", Qgis.Critical)
            logging.error(f"КРИТИЧЕСКАЯ ОШИБКА: {str(e)}", exc_info=True)
            self.set_progress(0, task)
            raise

    def _task_process_data(self, task, params):
        """Запуск расчёта внутри фоновой задачи QGIS."""
        self._active_task = task
        try:
            return self.process_data(params, task=task)
        finally:
            self._active_task = None

    def _on_processing_finished(self, exception, result=None):
        """Обработчик завершения фоновой задачи."""
        self.processing_task = None
        if exception is not None:
            QMessageBox.critical(self.dlg, "Ошибка", f"Произошла ошибка:\n\n{str(exception)}")
            self.update_progress(0)
            return
        if not result:
            QMessageBox.warning(self.dlg, "Предупреждение", "Обработка завершена без результата.")
            self.update_progress(0)
            return

        self.update_progress(100)
        msg = (
            f"Обработка завершена!\n\n"
            f"Рассчитано кратчайших маршрутов: {result['routes_count']}\n"
            f"Результаты: {result['output_dir']}\n"
            f"Время: {result['duration']:.2f} сек"
        )
        QMessageBox.information(self.dlg, "Готово", msg)

    def start_processing_task(self):
        """Создать и запустить фоновую задачу обработки."""
        if self.processing_task is not None:
            if self.processing_task.status() in (QgsTask.Queued, QgsTask.Running):
                QMessageBox.information(self.dlg, "Выполняется", "Расчёт уже выполняется.")
                return

        params = self.collect_processing_params()
        self.update_progress(0)
        self.processing_task = QgsTask.fromFunction(
            "Walkability analysis",
            self._task_process_data,
            on_finished=self._on_processing_finished,
            params=params
        )
        QgsApplication.taskManager().addTask(self.processing_task)
        self.log("Фоновая задача запущена")

    def setup_ui_connections(self):
        """Настройка связей UI."""
        self.dlg.REFRESH_SURFACE_WIDTH.clicked.connect(self.update_edges_fields)
