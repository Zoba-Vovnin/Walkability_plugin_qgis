    def export_nearest_routes_layer(self, nearest_routes, output_dir):
        """Экспорт слоя с кратчайшими путями."""
        if not nearest_routes:
            return
        
        fields = QgsFields()
        fields.append(QgsField("start", get_qvariant_type('String')))
        fields.append(QgsField("nearest_end", get_qvariant_type('String')))
        fields.append(QgsField("weight", get_qvariant_type('Double')))
        fields.append(QgsField("length", get_qvariant_type('Double')))
        fields.append(QgsField("time(minutes)", get_qvariant_type('Double')))
        fields.append(QgsField("vertices", get_qvariant_type('Int')))
        
        output_path = os.path.join(output_dir, "nearest_endpoint_routes.geojson")
        export_crs = QgsCoordinateReferenceSystem(EXPORT_CRS)
        
        transform = None
        if self.edges_crs and self.edges_crs.authid() != export_crs.authid():
            transform = QgsCoordinateTransform(self.edges_crs, export_crs, QgsProject.instance())
        
        if IS_QGIS4:
            options = QgsVectorFileWriter.SaveVectorOptions()
            options.driverName = "GeoJSON"
            options.fileEncoding = "UTF-8"
            
            writer = QgsVectorFileWriter.create(
                output_path, fields, QgsWkbTypes.LineString, export_crs,
                QgsProject.instance().transformContext(), options
            )
            
            if writer.hasError() != QgsVectorFileWriter.NoError:
                self.log(f"Ошибка создания файла", Qgis.Critical)
                return
        else:
            writer = QgsVectorFileWriter(
                output_path, "UTF-8", fields, QgsWkbTypes.LineString, export_crs, "GeoJSON"
            )
            
            if writer.hasError():
                self.log(f"Ошибка создания файла", Qgis.Critical)
                return
        
        for route in nearest_routes:
            feat = QgsFeature(fields)
            feat.setAttribute("start", route['start_name'])
            feat.setAttribute("nearest_end", route['end_name'])
            feat.setAttribute("weight", round(route['weight'], 6))
            
            # ВАЖНО: Длина вычисляется в EPSG:3857 (метры)
            # Координаты узлов из self.node_coords всегда в EPSG:3857
            # Результат всегда в метрах, независимо от CRS экспорта
            total_length = self.calculate_route_length_direct(route['path'])
            feat.setAttribute("length", round(total_length, 2))  # МЕТРЫ
            
            # Время: длина_в_метрах / скорость_м_мин (4 км/ч = 66.667 м/мин)
            time_val = total_length / 66.667 if total_length > 0 else 0.0
            feat.setAttribute("time(minutes)", round(time_val, 6))
            feat.setAttribute("vertices", route['vertices'])
            
            points = [self.node_coords[node] for node in route['path']]
            line_geom = QgsGeometry.fromPolylineXY(points)
            
            if transform:
                line_geom.transform(transform)
            
            feat.setGeometry(line_geom)
            writer.addFeature(feat)
        
        del writer
        self.log(f"✓ nearest_endpoint_routes.geojson ({len(nearest_routes)} маршрутов)")

    def log_nearest_endpoints_analysis(self, nearest_routes, start_points, end_points):
        """Логирование аналитического отчета."""
        if not nearest_routes:
            return
        
        endpoint_usage = defaultdict(int)
        weights_list = []
        lengths_list = []
        
        for route in nearest_routes:
            endpoint_usage[route['end_name']] += 1
            weights_list.append(route['weight'])
            total_length = self.calculate_route_length_direct(route['path'])
            lengths_list.append(total_length)
        
        avg_weight = sum(weights_list) / len(weights_list) if weights_list else 0
        avg_length = sum(lengths_list) / len(lengths_list) if lengths_list else 0
        
        logging.info("\n" + "=" * 70)
        logging.info("АНАЛИЗ КРАТЧАЙШИХ ПУТЕЙ")
        logging.info("=" * 70)
        logging.info(f"\nРассчитано маршрутов: {len(nearest_routes)}")
        logging.info(f"Средний вес: {avg_weight:.6f}")
        logging.info(f"Средняя длина: {avg_length:.2f} м")
        
        for idx, route in enumerate(nearest_routes, 1):
            total_length = self.calculate_route_length_direct(route['path'])
            logging.info(f"\nМаршрут #{idx}")
            logging.info(f"  {route['start_name']} → {route['end_name']}")
            logging.info(f"  Длина: {total_length:.2f} м")
        
        logging.info("=" * 70 + "\n")

