    def convert_to_point_geometry(self, layer):
        """Конвертирует полигональную геометрию в центроиды."""
        geom_type = layer.geometryType()
        
        # Проверка типа геометрии с учётом версии
        if IS_QGIS4:
            is_point = geom_type == QgsWkbTypes.GeometryType.PointGeometry
        else:
            is_point = geom_type == QgsWkbTypes.PointGeometry
        
        if is_point:
            self.log("Геометрия точечная, конвертация не нужна")
            return layer
        
        self.log("Конвертация полигонов → центроиды...")
        fields = layer.fields()
        point_layer = QgsVectorLayer(f"Point?crs={layer.crs().authid()}", "temp_points", "memory")
        point_layer.dataProvider().addAttributes(fields)
        point_layer.updateFields()
        
        features = []
        for feat in layer.getFeatures():
            geom = feat.geometry()
            if geom and not geom.isEmpty():
                centroid = geom.centroid()
                new_feat = QgsFeature(fields)
                new_feat.setGeometry(centroid)
                new_feat.setAttributes(feat.attributes())
                features.append(new_feat)
        
        point_layer.dataProvider().addFeatures(features)
        self.log(f"Конвертировано: {len(features)} объектов")
        return point_layer

    def load_layer_from_file(self, file_path, layer_name=None):
        """Загрузка слоя из файла с поддержкой множества форматов."""
        if not file_path or file_path == 'NULL':
            self.log(f"Путь к файлу пуст или равен 'NULL'", Qgis.Warning)
            return None
        
        if not os.path.exists(file_path):
            self.log(f"Файл не существует: {file_path}", Qgis.Warning)
            return None
        
        format_key, format_name, is_database = self.get_file_format(file_path)
        
        if format_key is None:
            self.log(f"Неизвестный формат файла: {file_path}\n"
                    f"Поддерживаемые форматы: {self.get_format_display_string()}", 
                    Qgis.Warning)
            return None
        
        provider = "ogr"
        uri = file_path
        
        if is_database and '|' not in file_path:
            temp_layer = QgsVectorLayer(file_path, "", "ogr")
            if not temp_layer.isValid():
                self.log(f"Не удалось открыть {format_name}: {file_path}", Qgis.Warning)
                return None
            
            sub_layers = temp_layer.dataProvider().subLayers()
            if not sub_layers:
                self.log(f"{format_name} не содержит векторных слоёв: {file_path}", Qgis.Warning)
                return None
            
            first_layer_info = sub_layers[0]
            if "!!::!!" in first_layer_info:
                first_layer = first_layer_info.split("!!::!!")[1]
            else:
                first_layer = first_layer_info
            
            uri = f"{file_path}|layername={first_layer}"
            self.log(f"{format_name}: автоматически выбран слой '{first_layer}'")
        
        layer = QgsVectorLayer(uri, layer_name or os.path.basename(file_path), provider)
        if not layer.isValid():
            error_msg = layer.error().message() if hasattr(layer.error(), 'message') else "Unknown error"
            self.log(f"Не удалось загрузить слой: {uri}\nОшибка: {error_msg}", Qgis.Warning)
            return None
        
        feat_count = layer.featureCount()
        if feat_count < 0:
            self.log(f"Слой загружен, но содержит невалидную геометрию: {file_path}", Qgis.Warning)
            return None
        
        if feat_count == 0:
            self.log(f"⚠ Слой загружен, но не содержит объектов: {file_path}", Qgis.Warning)
        
        geom_type_str = self.get_geometry_type_name(layer.geometryType())
        crs_str = layer.crs().authid() if layer.crs().isValid() else "No CRS"
        
        if not layer.crs().isValid():
            self.log(f"⚠ ВНИМАНИЕ: Слой загружен БЕЗ системы координат!", Qgis.Warning)
            logging.warning(f"Слой {os.path.basename(file_path)} загружен без CRS")
        
        self.log(f"✓ {format_name}: {os.path.basename(file_path)}")
        self.log(f"  Объектов: {feat_count}, Тип: {geom_type_str}, CRS: {crs_str}, Полей: {len(layer.fields())}")
        
        logging.info(f"Загружен {format_name}: {os.path.basename(file_path)} "
                    f"({feat_count} объектов, CRS: {crs_str})")
        
        return layer

    def preprocess_layer_for_analysis(self, layer, layer_label="Layer"):
        """
        Подготовка слоя для анализа:
        1) перепроекция в метрическую CRS (EPSG:3857),
        2) округление координат геометрии до COORD_PRECISION знаков.
        """
        if not layer or not layer.isValid():
            return layer

        target_crs = QgsCoordinateReferenceSystem(ANALYSIS_CRS)
        source_crs = layer.crs()
        need_transform = (
            source_crs is not None
            and source_crs.isValid()
            and source_crs.authid() != target_crs.authid()
        )

        transform = None
        if need_transform:
            transform = QgsCoordinateTransform(source_crs, target_crs, QgsProject.instance())
            self.log(f"{layer_label}: перепроекция {source_crs.authid()} → {target_crs.authid()}")
        elif source_crs is None or not source_crs.isValid():
            self.log(
                f"{layer_label}: CRS не определена, слой будет использован как {target_crs.authid()}",
                Qgis.Warning
            )

        wkb_name = QgsWkbTypes.displayString(layer.wkbType())
        prepped_layer = QgsVectorLayer(
            f"{wkb_name}?crs={target_crs.authid()}",
            f"{layer.name()}_prepped",
            "memory"
        )
        provider = prepped_layer.dataProvider()
        provider.addAttributes(layer.fields())
        prepped_layer.updateFields()

        prepared_features = []
        for feat in layer.getFeatures():
            geom = feat.geometry()
            if not geom or geom.isEmpty():
                continue

            geom_copy = QgsGeometry(geom)
            if transform is not None:
                try:
                    geom_copy.transform(transform)
                except Exception as e:
                    self.log(f"{layer_label}: ошибка перепроекции объекта {feat.id()}: {str(e)}", Qgis.Warning)
                    continue

            rounded_geom = QgsGeometry.fromWkt(geom_copy.asWkt(COORD_PRECISION))
            if not rounded_geom or rounded_geom.isEmpty():
                continue

            new_feat = QgsFeature(prepped_layer.fields())
            new_feat.setAttributes(feat.attributes())
            new_feat.setGeometry(rounded_geom)
            prepared_features.append(new_feat)

        provider.addFeatures(prepared_features)
        prepped_layer.updateExtents()
        self.log(
            f"{layer_label}: подготовлено объектов {len(prepared_features)} "
            f"(CRS={target_crs.authid()}, округление={COORD_PRECISION} знака)"
        )
        return prepped_layer

